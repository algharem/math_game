import 'enums.dart';

/// One filterable sub-topic of the curriculum map, e.g. `g4_p2_t2`.
/// Seeded into the local database and shown as a checkbox in exam setup.
class CurriculumTopic {
  const CurriculumTopic({
    required this.id,
    required this.grade,
    required this.part,
    required this.title,
    required this.unitName,
    this.pageReference,
    this.generationReady = true,
  });

  /// Stable identifier, e.g. `g4_p2_t2`.
  final String id;

  /// School grade 1–9.
  final int grade;

  /// Book part / semester (1 or 2).
  final int part;

  final String title;

  /// Loose grouping label for the exam header, e.g. «الأعداد والعمليات».
  final String unitName;

  /// Textbook page number when known — optional traceability only; exams
  /// never depend on it (topic ids and titles are the single source).
  final int? pageReference;

  /// All seeded book topics are exam-able; kept as a field so a future
  /// topic can be flagged false and shown disabled («قريباً»).
  final bool generationReady;

  CurriculumTopic copyWith({
    String? id,
    int? grade,
    int? part,
    String? title,
    String? unitName,
    int? pageReference,
    bool? generationReady,
  }) {
    return CurriculumTopic(
      id: id ?? this.id,
      grade: grade ?? this.grade,
      part: part ?? this.part,
      title: title ?? this.title,
      unitName: unitName ?? this.unitName,
      pageReference: pageReference ?? this.pageReference,
      generationReady: generationReady ?? this.generationReady,
    );
  }

  static const List<ExamMode> promptModes = ExamModeValues.all;

  /// Parse a topic id like `g4_p2_t2`.
  static RegExp get idPattern => RegExp(r'^g([1-9])_p([12])_t(\d+)$');
}

/// Exam modes offered on the exam setup screen.
enum ExamMode {
  quickPractice,
  fullExam,
  timedExam,
  adaptiveExam,
}

extension ExamModeX on ExamMode {
  String get label {
    switch (this) {
      case ExamMode.quickPractice:
        return 'اختبار سريع';
      case ExamMode.fullExam:
        return 'امتحان وحدة كامل';
      case ExamMode.timedExam:
        return 'امتحان مؤقّت';
      case ExamMode.adaptiveExam:
        return 'امتحان متكيّف';
    }
  }

  String get description {
    switch (this) {
      case ExamMode.quickPractice:
        return 'أسئلة قصيرة (٥–١٠) للمراجعة السريعة';
      case ExamMode.fullExam:
        return 'امتحان شامل (١٥–٢٠ سؤالاً) على المواضيع المختارة';
      case ExamMode.timedExam:
        return 'نموذج وزاري بالوقت (مؤقّت قابل للتخصيص)';
      case ExamMode.adaptiveExam:
        return 'الصعوبة تتغير تلقائياً حسب إجاباتك';
    }
  }

  int get defaultQuestionCount {
    switch (this) {
      case ExamMode.quickPractice:
        return 8;
      case ExamMode.fullExam:
      case ExamMode.timedExam:
        return 20;
      case ExamMode.adaptiveExam:
        return 15;
    }
  }

  int? get defaultDurationSeconds {
    switch (this) {
      case ExamMode.quickPractice:
      case ExamMode.fullExam:
      case ExamMode.adaptiveExam:
        return null;
      case ExamMode.timedExam:
        return 20 * 60;
    }
  }

  bool get isAdaptive => this == ExamMode.adaptiveExam;
}

class ExamModeValues {
  static const List<ExamMode> all = [
    ExamMode.quickPractice,
    ExamMode.fullExam,
    ExamMode.timedExam,
    ExamMode.adaptiveExam,
  ];
}

/// Filter parameters chosen by the parent/student on the exam setup screen.
class ExamFilterConfig {
  const ExamFilterConfig({
    required this.grade,
    required this.part,
    required this.selectedTopicIds,
    required this.questionCount,
    required this.difficultyLevel,
    this.examMode = ExamMode.quickPractice,
    this.durationSeconds,
  });

  final int grade; // 1 to 9
  final int part; // 1 or 2
  final List<String> selectedTopicIds;
  final int questionCount;

  /// Label of the requested strength: easy / medium / hard / mixed.
  final String difficultyLevel;

  final ExamMode examMode;
  final int? durationSeconds;

  Difficulty get difficulty {
    switch (difficultyLevel) {
      case 'easy':
        return Difficulty.easy;
      case 'hard':
        return Difficulty.hard;
      case 'mixed':
        return Difficulty.random;
      default:
        return Difficulty.medium;
    }
  }

  static const List<String> difficultyLevels = [
    'easy',
    'medium',
    'hard',
    'mixed',
  ];

  /// Question model placeholder — questions themselves are generated by
  /// the engine from [selectedTopicIds]; see TopicQuestionFactory.
  bool get isValid => selectedTopicIds.isNotEmpty;
}
